"""Post-hoc README + metadata generation for an existing trainset.h5.

Use when a preload job's main data step finished cleanly but the README
generation crashed (e.g., the import bug in `preload_loa_real.py` /
`preload_2lpt_simple.py` that wrote the trainset before the
`from preload_spectra._dataset_readme import …` line failed under
sys.path-bare envs like NERSC's `desi_environment.sh`).

Reconstructs README + dataset_metadata.json from the h5's own attrs and
shape — no rerun needed.

Usage::

    python preload_spectra/recover_dataset_readme.py \\
        path/to/trainset.h5 \\
        --kind loa_real    # or 2lpt_mock

Reads `output_h5.attrs` for provenance; falls back to defaults / TODO
strings for fields that weren't recorded as attrs.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import h5py


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("trainset_h5", type=Path)
    p.add_argument("--kind", choices=["loa_real", "2lpt_mock"], required=True)
    p.add_argument("--rest-min", type=float, default=None,
                   help="Override min_lambda from h5 attrs")
    p.add_argument("--rest-max", type=float, default=None,
                   help="Override max_lambda from h5 attrs")
    args = p.parse_args()

    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from _dataset_readme import write_dataset_readme

    if not args.trainset_h5.exists():
        sys.exit(f"[error] not found: {args.trainset_h5}")

    with h5py.File(args.trainset_h5, "r") as f:
        attrs = dict(f.attrs)
        n_spectra, n_pix = f["fluxes"].shape

    rest_min = args.rest_min if args.rest_min is not None else \
        float(attrs.get("min_lambda", 850.75))
    rest_max = args.rest_max if args.rest_max is not None else \
        float(attrs.get("max_lambda", 1420.75))
    dlambda = float(attrs.get("dlambda", 0.15))
    z_min = float(attrs.get("z_min", 2.0))
    z_max = float(attrs.get("z_max", 4.25))

    # Reconstruct filter pipeline from h5 attrs (best-effort)
    filter_pipeline = [f"z in [{z_min}, {z_max}] AND ZWARN==0 (if column exists)"]
    if attrs.get("exclude_bal", False):
        filter_pipeline.append("BAL anti-join: drop BI_CIV > 0")
    hcd_cat = attrs.get("hcd_cat", "")
    if hcd_cat:
        hcd_min_nhi = float(attrs.get("hcd_min_nhi", 17.2))
        sem = ("DLAs only" if hcd_min_nhi >= 20.3
               else "DLAs + sub-DLAs" if hcd_min_nhi >= 19.0
               else "all HCDs")
        filter_pipeline.append(
            f"HCD anti-join via {Path(str(hcd_cat)).name}: drop "
            f"TARGETIDs with logNHI ≥ {hcd_min_nhi} ({sem})"
        )

    sources = {
        "qsocat": str(attrs.get("qsocat", "")),
        "specdir": str(attrs.get("specdir", "")),
    }
    if hcd_cat:
        sources["hcd_cat"] = str(hcd_cat)

    cli_args_recovered = {
        "z_min": z_min, "z_max": z_max, "dlambda": dlambda,
        "exclude_bal": bool(attrs.get("exclude_bal", False)),
        "hcd_cat": str(hcd_cat) if hcd_cat else None,
        "hcd_min_nhi": float(attrs.get("hcd_min_nhi", 17.2)) if hcd_cat else None,
        "_recovered_post_hoc": True,
        "_recovery_note": "README generated by recover_dataset_readme.py, NOT "
                          "by the preload script itself (the preload's import "
                          "of _dataset_readme failed; trainset.h5 was complete).",
    }

    run_tag = args.trainset_h5.parent.name
    suggested_train = (f"sbatch --export=ALL,RUN_TAG={run_tag} "
                       f"slurm_train/train_only_nersc.sh")

    write_dataset_readme(
        args.trainset_h5,
        dataset_kind=args.kind,
        n_spectra=n_spectra,
        n_pix=n_pix,
        rest_min=rest_min,
        rest_max=rest_max,
        dlambda=dlambda,
        z_min=z_min,
        z_max=z_max,
        filter_pipeline=filter_pipeline,
        sources=sources,
        cli_args=cli_args_recovered,
        suggested_train_command=suggested_train,
    )

    print(f"[recover] wrote README.md + dataset_metadata.json next to "
          f"{args.trainset_h5}")
    print(f"          n_spectra={n_spectra}  n_pix={n_pix}  "
          f"rest [{rest_min}, {rest_max}] Å")


if __name__ == "__main__":
    main()
