"""joint_drop_count_validation.py — LLS-tier validation of the JOINT drop+count estimator
(`CDDF_analysis/hbi/joint_drop_count.py`) on the 2LPT-0 mock. Re-derivable, git-stamped —
replaces the plot-script literals the 2026-07-06 cross-check flagged (R0/band were never
guarded by re-execution). Reduce-only: NO inference, NO SLURM.

Builds the loa0 counting forward (nhi172 molly, op-cut to 17.2, fit_floor=19.5, pspline) EXACTLY
as the referee cache builder did, plus a PHYSICAL drop tau_hat(z912) summed DIRECTLY over the mock
HCD truth catalog (NOT generated by drop_tau_model — so the top-knot overflow, which cancels only
in a self-consistent synthetic drop, is genuinely exercised). Then:

  * HEADLINE (prior-free): lambda_mfp / tau_eff,LL. Fit kappa_912 to the truth tau_hat AND to the
    joint-MAP tau_model(theta), invert to lambda_mfp (proper Mpc), report R0_lambda = est/truth and
    the drop-fit reduced chi^2. This is the robust deliverable — a near-direct readout of the drop.
  * DERIVED (shape-limited): ell(X)[17.2,19.5). Report the joint-MAP ell + R0 for a canonical shape,
    AND the shape-marginalized band [q16,q50,q84] (lls_shape_marginalized_band, committed defaults
    lam_spline=60 / n_lap=400, single-PL slopes -1.9/-1.5/-1.1). The band is prior/shape-limited by
    construction (counts+drop under-determine ell — the panel's F1); truth is quoted for context but
    "brackets truth" is necessary-not-sufficient.
  * SANITY: drop=None reproduces the frozen counting-only fit; DLA-tier dN/dX(>=20.3) R0 ~ 1.1.

MOCK values only (public-OK). Real-LOA lambda_mfp/ell are private + PI-unblinding-gated.
"""
